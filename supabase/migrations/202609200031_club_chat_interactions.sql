create or replace function app_private.can_interact_chat(p_room uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and app_private.can_read_room(p_room) and exists(
 select 1 from public.chat_rooms r where r.id=p_room and not r.is_archived and r.deleted_at is null
 and (r.youth_id is null or app_private.is_youth_member(r.youth_id) or app_private.is_super_admin()));
$$;
create or replace function app_private.can_pin_chat(p_room uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select app_private.can_interact_chat(p_room) and exists(select 1 from public.chat_rooms r where r.id=p_room and (
 r.youth_id is not null or app_private.has_scope_permission('messages.pin',r.parish_id,r.youth_id)
 or app_private.has_scope_permission('chats.moderate',r.parish_id,r.youth_id)));
$$;
create or replace function app_private.can_manage_club_chats(p_youth uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and not app_private.is_restricted_guest(auth.uid()) and exists(
 select 1 from public.youth_groups g where g.id=p_youth and not g.is_archived
 and (app_private.is_super_admin() or app_private.is_club_admin(g.id)));
$$;

create or replace function app_private.bump_chat_interactions() returns trigger
language plpgsql security definer set search_path='' as $$
declare room uuid;
begin
 room:=case when tg_op='DELETE' then old.room_id else new.room_id end;
 if exists(select 1 from public.chat_rooms where id=room) then
  insert into public.chat_interaction_changes(room_id) values(room)
   on conflict(room_id) do update set revision=public.chat_interaction_changes.revision+1;
 end if;
 return null;
end $$;
drop trigger if exists chat_pins_changed on public.chat_message_pins;
create trigger chat_pins_changed after insert or update or delete on public.chat_message_pins for each row execute function app_private.bump_chat_interactions();
drop trigger if exists chat_reactions_changed on public.chat_message_reactions;
create trigger chat_reactions_changed after insert or delete on public.chat_message_reactions for each row execute function app_private.bump_chat_interactions();

create or replace function app_private.cleanup_chat_interactions() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if new.deleted_at is not null and old.deleted_at is null then
  delete from public.chat_message_pins where room_id=new.room_id and message_id=new.id;
  delete from public.chat_message_reactions where room_id=new.room_id and message_id=new.id;
  insert into public.chat_interaction_changes(room_id) values(new.room_id)
   on conflict(room_id) do update set revision=public.chat_interaction_changes.revision+1;
 end if;
 return null;
end $$;
drop trigger if exists message_interactions_cleanup on public.chat_messages;
create trigger message_interactions_cleanup after update of deleted_at on public.chat_messages for each row execute function app_private.cleanup_chat_interactions();

