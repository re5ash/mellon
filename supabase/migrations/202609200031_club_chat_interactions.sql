create or replace function public.chat_capabilities(p_room uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare r public.chat_rooms;
begin
 select * into r from public.chat_rooms where id=p_room;
 if not found or not app_private.can_read_room(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 return jsonb_build_object('send',not r.is_archived and app_private.has_scope_permission(case when r.kind='channel' then 'channels.publish' else 'chat.send' end,r.parish_id,r.youth_id),
 'delete_own',app_private.has_scope_permission('messages.delete_own',r.parish_id,r.youth_id),
 'delete_any',app_private.has_scope_permission('messages.delete_any',r.parish_id,r.youth_id) or app_private.has_scope_permission('chats.moderate',r.parish_id,r.youth_id),
 'pin',app_private.can_pin_chat(p_room),'react',app_private.can_interact_chat(p_room));
end $$;

create or replace function public.chat_history_v2(p_room uuid,p_before timestamptz default null,p_before_id uuid default null,p_anchor uuid default null) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 -- Delegate membership, visibility and stable pagination to the existing history.
 return (select coalesce(jsonb_agg(to_jsonb(h)||jsonb_build_object('reply',case when parent.id is null then null else
 jsonb_build_object('id',parent.id,'author_name',author.display_name,'body',case when parent.deleted_at is not null then 'Сообщение удалено' else left(parent.body,160) end,'deleted',parent.deleted_at is not null) end)
 order by h.created_at desc,h.id desc),'[]'::jsonb)
 from public.chat_history(p_room,p_before,p_before_id,p_anchor) h
 join public.chat_messages original on original.id=h.id
 left join public.chat_messages parent on parent.room_id=h.room_id and parent.id=original.reply_to
 left join public.profiles author on author.id=parent.author_id);
end $$;

create or replace function public.chat_interactions(p_room uuid,p_messages uuid[]) returns jsonb
language plpgsql stable security definer set search_path='' as $$
declare pins jsonb; reactions jsonb;
begin
 if not app_private.can_read_room(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 if cardinality(p_messages)>100 then raise exception 'invalid_page' using errcode='22023'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('message_id',m.id,'author_name',a.display_name,'body',left(m.body,160),'pinned_at',p.pinned_at)
 order by p.pinned_at desc,m.id desc),'[]'::jsonb) into pins
 from public.chat_message_pins p join public.chat_messages m on m.id=p.message_id and m.room_id=p.room_id
 join public.profiles a on a.id=m.author_id where p.room_id=p_room and m.deleted_at is null;
 select coalesce(jsonb_agg(to_jsonb(t) order by t.message_id,t.emoji),'[]'::jsonb) into reactions from(
 select r.message_id,r.emoji,count(*)::integer as count,bool_or(r.user_id=auth.uid()) as mine
 from public.chat_message_reactions r join public.chat_messages m on m.room_id=r.room_id and m.id=r.message_id
 where r.room_id=p_room and r.message_id=any(coalesce(p_messages,'{}'::uuid[])) and m.deleted_at is null
 group by r.message_id,r.emoji)t;
 return jsonb_build_object('pins',pins,'reactions',reactions);
end $$;

create or replace function public.set_chat_reaction(p_room uuid,p_message uuid,p_emoji text,p_selected boolean,p_expected_user uuid) returns void
language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or auth.uid() is distinct from p_expected_user then raise exception 'forbidden' using errcode='42501'; end if;
 perform 1 from public.chat_rooms where id=p_room for share;
 if not found or not app_private.can_interact_chat(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 perform 1 from public.chat_messages where id=p_message and room_id=p_room and deleted_at is null for share;
 if not found then raise exception 'message_unavailable' using errcode='22023'; end if;
 if p_selected is null or not exists(select 1 from app_private.chat_reaction_emoji where emoji=p_emoji) then raise exception 'invalid_reaction' using errcode='22023'; end if;
 if p_selected then
 insert into public.chat_message_reactions(room_id,message_id,user_id,emoji) values(p_room,p_message,auth.uid(),p_emoji) on conflict do nothing;
 else delete from public.chat_message_reactions where room_id=p_room and message_id=p_message and user_id=auth.uid() and emoji=p_emoji; end if;
end $$;

create or replace function public.set_chat_message_pin(p_room uuid,p_message uuid,p_pinned boolean,p_expected_user uuid) returns void
language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or auth.uid() is distinct from p_expected_user then raise exception 'forbidden' using errcode='42501'; end if;
 perform 1 from public.chat_rooms where id=p_room for update;
 if not found or not app_private.can_pin_chat(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 if p_pinned is null then raise exception 'invalid_pin' using errcode='22023'; end if;
 if p_pinned then
 perform 1 from public.chat_messages where id=p_message and room_id=p_room and deleted_at is null;
 if not found then raise exception 'message_unavailable' using errcode='22023'; end if;
 insert into public.chat_message_pins(room_id,message_id,pinned_by) values(p_room,p_message,auth.uid()) on conflict do nothing;
 else
 delete from public.chat_message_pins where room_id=p_room and message_id=p_message;
 delete from public.chat_pins where room_id=p_room and message_id=p_message;
 end if;
end $$;

create or replace function public.send_chat_reply(p_room uuid,p_body text,p_reply_to uuid,p_nonce uuid,p_expected_user uuid) returns public.chat_messages
language plpgsql security definer set search_path='' as $$
declare m public.chat_messages;
begin
 if auth.uid() is null or auth.uid() is distinct from p_expected_user then raise exception 'forbidden' using errcode='42501'; end if;
 -- Same lock order as send_message; retries retain the original reply target.
 perform 1 from public.profiles where id=auth.uid() for update;
 perform 1 from public.chat_rooms where id=p_room for share;
 if not found or not app_private.can_read_room(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 select * into m from public.chat_messages where author_id=auth.uid() and client_nonce=p_nonce;
 if found then
  if m.room_id is distinct from p_room or m.reply_to is distinct from p_reply_to or m.body is distinct from btrim(p_body) then raise exception 'nonce_conflict' using errcode='22023'; end if;
  return m;
 end if;
 perform 1 from public.chat_messages where id=p_reply_to and room_id=p_room and deleted_at is null for share;
 if not found then raise exception 'message_unavailable' using errcode='22023'; end if;
 m:=public.send_message(p_room,p_body,p_nonce);
 update public.chat_messages set reply_to=p_reply_to where id=m.id returning * into m;
 return m;
end $$;

-- Older clients keep their single-pin API, while sharing the same records.
create or replace function public.current_chat_pin(p_room uuid) returns jsonb
language plpgsql stable security definer set search_path='' as $$
begin
 if not app_private.can_read_room(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 return (public.chat_interactions(p_room,'{}'::uuid[])->'pins'->0);
end $$;
create or replace function public.set_chat_pin(p_room uuid,p_message uuid,p_expected_user uuid) returns void
language plpgsql security definer set search_path='' as $$
begin
 if p_message is not null then perform public.set_chat_message_pin(p_room,p_message,true,p_expected_user);
 else
 if auth.uid() is null or auth.uid() is distinct from p_expected_user then raise exception 'forbidden' using errcode='42501'; end if;
 perform 1 from public.chat_rooms where id=p_room for update;
 if not app_private.can_pin_chat(p_room) then raise exception 'forbidden' using errcode='42501'; end if;
 delete from public.chat_message_pins where room_id=p_room;
 delete from public.chat_pins where room_id=p_room;
 end if;
end $$;

