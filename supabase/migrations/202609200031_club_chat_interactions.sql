begin
 if old.youth_id is not null and auth.uid() is not null and
 (new.title,new.icon_key,new.deleted_at) is distinct from (old.title,old.icon_key,old.deleted_at)
 and not app_private.can_manage_club_chats(old.youth_id) then raise exception 'forbidden' using errcode='42501'; end if;
