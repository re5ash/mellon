create or replace function public.edit_club_chat_meta(p_youth uuid,p_room uuid,p_title text,p_icon text,p_revision bigint,p_expected_user uuid) returns void
language plpgsql security definer set search_path='' as $$
declare r public.chat_rooms;
begin
 if auth.uid() is null or auth.uid() is distinct from p_expected_user then raise exception 'forbidden' using errcode='42501'; end if;
 perform pg_advisory_xact_lock(120010);
 if not app_private.can_manage_club_chats(p_youth) then raise exception 'forbidden' using errcode='42501'; end if;
 select * into r from public.chat_rooms where id=p_room and youth_id=p_youth and deleted_at is null for update;
 if not found then raise exception 'chat_unavailable' using errcode='22023'; end if;
 if p_title is null and p_icon is null then return; end if;
 if p_title is not null and length(btrim(p_title)) not between 1 and 100 or p_icon is not null and not app_private.valid_chat_icon(p_icon) then raise exception 'invalid_chat' using errcode='22023'; end if;
 if (coalesce(btrim(p_title),r.title),coalesce(p_icon,r.icon_key)) is not distinct from (r.title,r.icon_key) then return; end if;
 if p_revision is null or p_revision is distinct from r.revision then raise exception 'edit_conflict' using errcode='40001'; end if;
 update public.chat_rooms set title=coalesce(btrim(p_title),title),icon_key=coalesce(p_icon,icon_key) where id=p_room;
 insert into app_private.audit_log(actor_id,action,entity_type,entity_id,parish_id,metadata)
 values(auth.uid(),'chat.edit','chat_room',p_room,r.parish_id,jsonb_build_object('youth',p_youth));
end $$;

